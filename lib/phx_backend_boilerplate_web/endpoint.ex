defmodule PhxBackendBoilerplateWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :phx_backend_boilerplate
  use Absinthe.Phoenix.Endpoint

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_phx_backend_boilerplate_key",
    signing_salt: "UjhXLSqq",
    same_site: "Lax"
  ]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  socket "/socket", PhxBackendBoilerplateWeb.UserSocket,
    websocket: true,
    longpoll: false

  socket "/graphql", PhxBackendBoilerplateWeb.GraphqlSocket,
    websocket: true,
    longpoll: false

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :phx_backend_boilerplate,
    gzip: not code_reloading?,
    only: PhxBackendBoilerplateWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :phx_backend_boilerplate
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  plug PhxBackendBoilerplateWeb.Plugs.RequestContext
  plug PhxBackendBoilerplateWeb.Plugs.SecurityHeaders
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug PhxBackendBoilerplateWeb.Plugs.Parsers,
    parsers: [:urlencoded, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library(),
    body_reader: {PhxBackendBoilerplateWeb.Plugs.CacheBodyReader, :read_body, []},
    length: Application.compile_env(:phx_backend_boilerplate, [:parsers, :length], 8_000_000)

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options

  # CORS must run before the router so OPTIONS preflight never hits controllers.
  # Origins are resolved at request time from `:cors` config (see runtime.exs).
  plug CORSPlug,
    origin: &__MODULE__.cors_origins/0,
    credentials: true,
    max_age: 86_400,
    methods: ["GET", "HEAD", "POST", "PUT", "PATCH", "DELETE", "OPTIONS"],
    headers: [
      "Authorization",
      "Content-Type",
      "Accept",
      "Origin",
      "X-Request-Id",
      "X-Correlation-Id",
      "X-Guest-Id",
      "X-Device-Fingerprint",
      "X-User-Id",
      "X-Request-Timeout-Ms"
    ],
    expose: [
      "x-guest-id",
      "x-correlation-id",
      "retry-after",
      "accept-ranges",
      "content-range"
    ]

  plug PhxBackendBoilerplateWeb.Router

  @doc false
  def cors_origins do
    :phx_backend_boilerplate
    |> Application.get_env(:cors, [])
    |> Keyword.get(:origins, [])
  end
end
