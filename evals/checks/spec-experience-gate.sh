#!/bin/bash
set -euo pipefail

skill=".cursor/skills/spec/SKILL.md"
design_skill=".cursor/skills/design-experience/SKILL.md"
template="intent/_templates/spec.md"
plan_skill=".cursor/skills/plan/SKILL.md"
plan_template="intent/_templates/plan.md"
orchestrate_skill=".cursor/skills/orchestrate/SKILL.md"
orchestrator=".cursor/agents/orchestrator.md"
verifier=".cursor/agents/verifier.md"
rule=".cursor/rules/intent-artifacts.mdc"
separation=".cursor/rules/review-separation.mdc"
case_file="evals/cases/coding/spec-experience-gate.json"

grep -q '^description: Use when ' "$skill"
grep -q '^disable-model-invocation: true$' "$skill"
grep -q 'apply every relevant skill' "$skill"
grep -q 'changes information a user sees or an action a user takes' "$design_skill"
grep -q 'Status is `accepted`' "$design_skill"
grep -q '^Experience: UX-NNN | none$' "$template"
grep -q 'user-visible behavior cites one or more accepted UX-NNN' "$skill"
grep -q 'Experience: none' "$skill"
grep -q '`Experience: UX-NNN | none`' "$plan_skill"
grep -q 'applicable states covered' "$plan_skill"
grep -q '^Experience: UX-NNN | none$' "$plan_template"
grep -q '^States covered:$' "$plan_template"
grep -q 'browser or end-to-end evidence' "$plan_template"
grep -q 'draft experience goes to `ux-reviewer`' "$orchestrate_skill"
grep -q '`ux-reviewer` follows `verifier`' "$orchestrate_skill"
grep -q 'draft experience goes to `ux-reviewer`' "$orchestrator"
grep -q 'applicable accepted state:' "$verifier"
grep -q 'experience.md' "$rule"
grep -q 'accepted' "$rule"
grep -q 'ux-reviewer' "$separation"
grep -q 'experience' "$separation"
grep -q 'experience.md does not exist' "$case_file"

echo "spec experience gate: OK"
