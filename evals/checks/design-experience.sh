#!/bin/bash
set -euo pipefail

skill=".cursor/skills/design-experience/SKILL.md"
template="intent/_templates/experience.md"
reviewer=".cursor/agents/ux-reviewer.md"
case_file="evals/cases/coding/design-experience.json"

test -f "$skill"
test -f "$template"
test -f "$reviewer"
test -f "$case_file"
grep -q '^name: design-experience$' "$skill"
grep -q '^description: Use when ' "$skill"
grep -q '^disable-model-invocation: true$' "$skill"
grep -q 'Status is `accepted`' "$skill"
grep -q '^Status: draft | accepted$' "$template"
grep -q '^## Primary journey$' "$template"
grep -q '^## Interaction states$' "$template"
grep -q '^Empty:$' "$template"
grep -q '^Partial failure:$' "$template"
grep -q '^Permission denied:$' "$template"
grep -q '^## Confirmation, recovery and destructive actions$' "$template"
grep -q '^### UX-001$' "$template"
grep -q '^Given:$' "$template"
grep -q '^When:$' "$template"
grep -q '^Then:$' "$template"
grep -q '^## Alternatives and trade-offs$' "$template"
grep -q '^## Assumptions and open questions$' "$template"
grep -q 'Do not convert an "obvious" choice' "$skill"
grep -q 'Do not set `accepted`' "$skill"
grep -q '^readonly: true$' "$reviewer"
grep -q 'Do not suggest improvements. Report failures only.' "$reviewer"
grep -q 'Do not edit artifacts or' "$reviewer"
grep -q 'List every UX decision you inferred' "$case_file"

echo "design experience: OK"
